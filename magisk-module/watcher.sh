#!/system/bin/sh
# Event-driven watcher for Storage Isolation's configuration.
#
# inotifyd blocks on the directory and runs a program for every matching event, so there is no
# idle polling: the CPU only wakes up when Storage Isolation actually writes its configuration.
#
# The directory is watched rather than the file because a save that replaces the file (write
# temp + rename) would make a file watch die with a DELETE event.
#
# inotifyd mask letters (toybox): a c e w r D M u n d m y
#   c = content modified, e = metadata, w = closed-after-write, n/m/d = create/move/delete
# The mask must be written as one token ("cwenmd"); comma-separated lists are rejected.

MODDIR=${0%/*}
LOG=/data/local/tmp/si-provider-fix.log
CONFIG_DIR=/data/adb/storage-isolation
INOTIFY_PIDFILE=/data/local/tmp/si-provider-fix.inotifyd.pid

log() {
    echo "$(date '+%m-%d %H:%M:%S') $*" >> "$LOG"
    lines=$(wc -l < "$LOG" 2>/dev/null || echo 0)
    if [ "$lines" -gt 400 ]; then
        tail -n 200 "$LOG" > "$LOG.tmp" 2>/dev/null && mv -f "$LOG.tmp" "$LOG"
    fi
}

# inotifyd invokes: PROG EVENTS FILE [DIRFILE]
# The trampoline bakes in the real module directory so it keeps working whichever path the
# module currently lives at (modules/ vs modules_update/ during an upgrade).
TRAMPOLINE=/data/local/tmp/si-provider-fix.trigger
{
    echo '#!/system/bin/sh'
    echo "# auto-generated by watcher.sh; module dir baked in"
    echo "MODDIR='$MODDIR'"
    cat <<'EOF'
# $1 = event letters, $2 = watched path, $3 = filename (when watching a directory)
case "$3" in
    configuration.json|"") ;;
    *) exit 0 ;;
esac
case "$1" in
    *c*|*w*|*e*|*m*|*n*)
        sh "$MODDIR/push_rules.sh" >/dev/null 2>&1
        ;;
esac
exit 0
EOF
} > "$TRAMPOLINE"
chmod 755 "$TRAMPOLINE"

log "watcher start pid=$$ module_dir=$MODDIR"

# initial push so rules are valid even before the first edit
sh "$MODDIR/push_rules.sh" >> "$LOG" 2>&1

while true; do
    inotifyd "$TRAMPOLINE" "$CONFIG_DIR:cwenmd" >> "$LOG" 2>&1 &
    IPID=$!
    echo "$IPID" > "$INOTIFY_PIDFILE"
    log "inotifyd started pid=$IPID"

    wait "$IPID"
    rc=$?
    log "inotifyd exited rc=$rc, restarting in 2s"
    sleep 2
done
